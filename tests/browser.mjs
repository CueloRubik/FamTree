import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',d=>d.accept());
try{
 await page.goto('http://127.0.0.1:8000');
 await page.waitForFunction(()=>document.querySelector('#modeBadge').textContent.includes('Ejemplo'));
 assert.equal(await page.locator('.leaf-node').count(),10);
 await page.locator('#query').fill('Julian');
 await page.locator('#results button').first().click();
 assert.match(await page.locator('#detail h2').textContent(),/Julián/);
 await page.locator('#scope').selectOption('descendants');
 assert.equal(await page.locator('.leaf-node').count(),7);
 await page.locator('[data-view="directory"]').click();
 assert.equal(await page.locator('#directory .person-row').count(),1);
 await page.locator('#query').fill('');
 assert.equal(await page.locator('#directory .person-row').count(),10);
 await page.locator('[data-view="timeline"]').click();
 assert.ok(await page.locator('#timeline .event').count()>10);
 await page.locator('#localMode').click();
 assert.equal(await page.locator('.leaf-node').count(),0);
 async function add(name,status,birth,notes,publish=false){
  await page.locator('#add').click();
  await page.locator('[name="name"]').fill(name);
  await page.locator('[name="status"]').selectOption(status);
  await page.locator('[name="birth"]').fill(birth);
  await page.locator('[name="notes"]').fill(notes);
  if(publish)await page.locator('[name="publish"]').check();
  await page.locator('#personForm button[type=submit]').click();
  await page.waitForFunction(()=>!document.querySelector('#personDialog').open);
 }
 await add('Persona ficticia uno','deceased','1900','nota privada',true);
 await add('Persona ficticia dos','living','2000','dato ficticio privado');
 assert.equal(await page.locator('.leaf-node').count(),2);
 await page.getByRole('button',{name:'Añadir vínculo',exact:true}).click();
 await page.locator('#relationForm button[type=submit]').click();
 assert.equal(await page.locator('#countLinks').textContent(),'1');
 await page.locator('#undo').click();
 assert.equal(await page.locator('#countLinks').textContent(),'0');
 await page.locator('#redo').click();
 assert.equal(await page.locator('#countLinks').textContent(),'1');
 await page.getByRole('button',{name:'Editar',exact:true}).click();
 await page.locator('[name="name"]').fill('Persona ficticia dos editada');
 await page.locator('#personForm button[type=submit]').click();
 assert.match(await page.locator('#detail h2').textContent(),/editada/);
 const privateDownload=page.waitForEvent('download');await page.locator('#export').click();
 const privateFile=await privateDownload;const privateData=JSON.parse(readFileSync(await privateFile.path(),'utf8'));
 assert.equal(privateData.people.length,2);
 const publicDownload=page.waitForEvent('download');await page.locator('#publish').click();
 const publicFile=await publicDownload;const publicData=JSON.parse(readFileSync(await publicFile.path(),'utf8'));
 assert.equal(publicData.people.length,1);assert.equal(publicData.people[0].notes,'');assert.equal(publicData.relations.length,0);
 await page.locator('#file').setInputFiles({name:'sample.private.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(privateData))});
 await page.waitForFunction(()=>document.querySelector('#countPeople').textContent==='2');
 await page.locator('#theme').click();assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.locator('#publicMode').click();assert.equal(await page.locator('#countPeople').textContent(),'0');
 await page.locator('#demoMode').click();
 await page.setViewportSize({width:390,height:844});
 await page.locator('#fit').click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2));
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('Browser smoke checks passed: demo, search, navigation, relations, edit, history, exports, import, theme and mobile width.');
}finally{await browser.close()}
